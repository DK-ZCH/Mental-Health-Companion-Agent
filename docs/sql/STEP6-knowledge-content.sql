温和而直接地询问，并不是在「提醒」对方去做什么，反而可以让对方知道你愿意认真听。问的时候认真听，不评判，不说「想开点」「别人比你难多了」；不要轻易承诺「我替你保密」，可以先告诉对方「这件事我会和你一起想办法」；如果已经存在明确而紧迫的安全风险，不要为了保密而阻止必要的求助，应尽量不要让对方独处，并尽快联系能够及时提供帮助的人。

三、把专业的支持接进来

把情况告诉学校心理中心、信任的老师，或者陪同前往就近的医院急诊。如果已经存在紧迫的安全风险，可以陪同前往就近的医院急诊，并联系能够及时到场、值得信任的人共同提供支持。你不是要独自解决一切——你的角色是那座把人和专业帮助连起来的桥，桥不需要自己扛住所有重量。

记住先后顺序：先确保当下的安全；若风险紧迫，尽量不让对方独处，再尽快接上专业的人。你不需要当场解决对方的痛苦，也解决不了；把人带到能够获得专业帮助的地方，就是非常重要的一步。

事后，无论结果如何，也请记得：你愿意认真对待并寻求帮助，本身就是一件重要的事。

小结：可以带走的三点。其一，出现信号时与其假定没事，不如认真问一问。其二，直接温和地问，陪伴而不评判，不轻易承诺保密。其三，尽快接上专业支持，你的角色是桥。

